// Lossy WebP holds BT.601 limited-range Y'CbCr. Both decoders must convert
// it as libwebp does: the pure-Go one (CGO_ENABLED=0) used Go's full-range
// JFIF matrix, which read 10,20,30 as 25,33,42 and 250 as 231.
func TestDecodeWebP_LossyColours(t *testing.T) {
	for _, tt := range []struct {
		name  string
		data  []byte
		alpha uint8 // of the right block
	}{
		{"opaque", lossyRGB, 255},
		{"alpha", lossyRGBA, 200},
	} {
		img, err := DecodeImage(tt.data, "webp")
		if err != nil {
			t.Fatalf("%s: %v", tt.name, err)
		}
		pixel := func(x, y int) [4]uint8 {
			if rgba, ok := img.(*image.RGBA); ok { // straight alpha
				return [4]uint8(rgba.Pix[rgba.PixOffset(x, y):][:4])
			}
			r, g, b, a := img.At(x, y).RGBA() // opaque types
			return [4]uint8{uint8(r >> 8), uint8(g >> 8), uint8(b >> 8), uint8(a >> 8)}
		}
		for _, p := range []struct {
			x    int
			want [4]uint8
		}{
			// Away from the block edge, where libwebp interpolates chroma
			// and compression noise sits.
			{2, [4]uint8{10, 20, 30, 255}},
			{6, [4]uint8{10, 20, 30, 255}},
			{26, [4]uint8{250, 250, 250, tt.alpha}},
			{30, [4]uint8{250, 250, 250, tt.alpha}},
		} {
			got := pixel(p.x, 8)
			for c := range 4 {
				if d := int(got[c]) - int(p.want[c]); d < -2 || d > 2 {
					t.Errorf("%s: pixel (%d,8) = %v, want %v within 2", tt.name, p.x, got, p.want)
					break
				}
			}
		}
	}
}
